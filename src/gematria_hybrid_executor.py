class HybridExecutor:
    """Hybrid CPU/GPU executor with assembly generation"""
    
    def __init__(self, use_cuda: bool = True):
        self.analyzer = OpcodeAnalyzer()
        self.cpu_gen = CPUAssemblyGenerator()
        self.gpu_gen = GPUKernelGenerator(use_cuda)
        self.use_cuda = use_cuda
        
        # Try to import GPU runner
        try:
            from .gematria_gpu_runner import GematriaGPUInterpreter
            self.gpu_interpreter = GematriaGPUInterpreter(use_cuda)
            self.gpu_available = True
        except ImportError:
            self.gpu_available = False
            # print("GPU runner not available, falling back to CPU")
        
        # Import CPU interpreter
        from .gematria_compiler import BytecodeInterpreter
        self.cpu_interpreter = BytecodeInterpreter()
    
    def execute_program(self, bytecode: bytes, program_name: str = "") -> Dict:
        """Execute a program on the optimal target"""
        # Analyze bytecode
        analysis = self.analyzer.analyze_bytecode(bytecode)
        target = analysis['target']
        
        result = {
            'program': program_name,
            'target': target.value,
            'reason': analysis['reason'],
            'assembly': '',
            'output': '',
            'output_length': 0,
            'success': True
        }
        
        # Generate assembly based on target
        if target == ExecutionTarget.CPU or target == ExecutionTarget.HYBRID:
            result['assembly'] = self.cpu_gen.generate_assembly(bytecode, program_name)
        
        if target == ExecutionTarget.GPU or target == ExecutionTarget.HYBRID:
            if self.use_cuda:
                result['gpu_kernel'] = self.gpu_gen.generate_cuda_kernel(bytecode, program_name)
            else:
                result['gpu_kernel'] = self.gpu_gen.generate_opencl_kernel(bytecode, program_name)
        
        # Execute on appropriate target
        try:
            if target == ExecutionTarget.GPU and self.gpu_available:
                # Execute on GPU
                output, output_len = self.gpu_interpreter.run_bytecode(bytecode)
                result['output'] = output
                result['output_length'] = output_len
            else:
                # Execute on CPU
                from .gematria_compiler import BytecodeInterpreter
                interpreter = BytecodeInterpreter()
                interpreter.load_bytecode(bytecode)
                output = interpreter.run(interactive=False)
                result['output'] = ''.join(output)
                result['output_length'] = len(output)
        except Exception as e:
            result['output'] = f"Error: {str(e)}"
            result['output_length'] = 0
            result['success'] = False
        
        return result

